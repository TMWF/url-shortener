// Пакет main реализует multichecker — инструмент статического анализа,
// объединяющий стандартные анализаторы, правила из staticcheck.io, сторонние
// популярные линтеры и собственное правило, запрещающее вызов os.Exit в функции main.
//
// # Механизм запуска
//
// Для сборки и запуска утилиты выполните следующие команды из корня вашего проекта:
//
//	# Сборка бинарного файла
//	go build -o staticlint ./cmd/staticlint
//
//	# Запуск анализа для всего проекта (включая подпакеты)
//	./staticlint ./...
//
//	# Также поддерживается запуск напрямую через go run:
//	go run ./cmd/staticlint ./...
//
// # Список входящих анализаторов
//
// 1. Стандартные статические анализаторы из пакета golang.org/x/tools/go/analysis/passes:
//   - asmdecl: проверяет несоответствия между объявлениями ассемблера и Go.
//   - assign: проверяет на наличие бесполезных присваиваний.
//   - atomic: проверяет корректность использования функций пакета sync/atomic.
//   - bools: находит очевидные ошибки в булевых операциях.
//   - buildtag: проверяет правильность форматирования тегов сборки (+build и go:build).
//   - cgocall: проверяет правила передачи указателей в cgo.
//   - composite: находит неименованные инициализации структур (без указания ключей).
//   - copylock: проверяет, не копируются ли типы, содержащие Lock (например, sync.Mutex).
//   - errorsas: проверяет, что второй аргумент errors.As является указателем на интерфейс или ошибку.
//   - httpresponse: предотвращает типичные ошибки с незакрытыми или забытыми HTTP-ответами.
//   - loopclosure: находит ссылки на переменные цикла внутри отложенных (defer) или горутинных вызовов.
//   - lostcancel: проверяет, что функция context.CancelFunc всегда вызывается.
//   - nilfunc: находит сравнения функций с nil, которые всегда ложны.
//   - printf: проверяет соответствие аргументов строкам форматирования в семействе printf.
//   - shift: проверяет сдвиги, превышающие размер типа данных.
//   - stdmethods: проверяет сигнатуры стандартных методов (например, Write, Read, MarshalJSON).
//   - structtag: валидирует синтаксис Go-тегов в структурах.
//   - tests: проверяет некорректные сигнатуры тестов и примеров (Example).
//   - unmarshal: находит передачу не-указателей в функции unmarshal.
//   - unreachable: находит недостижимый (мертвый) код.
//   - unsafeptr: проверяет безопасность преобразований в unsafe.Pointer.
//   - unusedresult: предупреждает о неиспользованных результатах вызова чистых функций.
//
// 2. Анализаторы класса SA (Staticcheck) из пакета staticcheck.io:
//   - Все правила группы SA (например, SA1000, SA4000, SA9000 и др.), нацеленные на
//     обнаружение багов, утечек памяти, некорректного использования стандартной библиотеки и проблем производительности.
//
// 3. Анализаторы других классов из пакета staticcheck.io:
//   - S1000 (simple): предлагает заменить single-case select на операцию с каналом.
//   - ST1000 (stylecheck): проверяет форматирование и наличие документации к пакетам.
//   - QF1001 (quickfix): предлагает упростить вызовы, например, использовать strings.Contains вместо strings.Index.
//
// 4. Публичные сторонние анализаторы:
//   - bodyclose (github.com/timakin/bodyclose): проверяет, что тело HTTP-ответа (res.Body) всегда закрывается.
//   - nilerr (github.com/gostaticanalysis/nilerr): находит ситуации, когда проверяется ошибка, но возвращается nil.
//
// 5. Собственный анализатор (osexit):
//   - Запрещает использовать прямой вызов os.Exit() в функции main пакета main.
