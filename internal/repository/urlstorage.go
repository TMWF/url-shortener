package repository

import (
	"context"

	"github.com/TMWF/url-shortener/internal/model"
)

// URLStorage описывает хранилище URL.
//
// Интерфейс инкапсулирует операции сохранения исходных URL, получения исходного
// URL по идентификатору короткой ссылки, пакетного сохранения URL и получения
// списка ссылок, принадлежащих текущему пользователю.
//
// Реализации URLStorage должны использовать переданный context.Context для
// отмены операций, контроля времени выполнения и получения дополнительных данных,
// например идентификатора пользователя.
type URLStorage interface {
	// SaveURL сохраняет исходный URL и возвращает идентификатор короткой ссылки.
	//
	// Возвращает ошибку, если URL не удалось сохранить или если в хранилище
	// произошёл конфликт либо другая внутренняя ошибка.
	SaveURL(ctx context.Context, url string) (string, error)

	// GetURL возвращает исходный URL по идентификатору короткой ссылки.
	//
	// Возвращает ошибку, если URL не найден, был удалён или произошла ошибка
	// при обращении к хранилищу.
	GetURL(ctx context.Context, id string) (string, error)

	// SaveBatchURL сохраняет набор исходных URL.
	//
	// Принимает список элементов model.URLBatchRequestDto и возвращает список
	// идентификаторов коротких ссылок в порядке, соответствующем входному набору.
	// Возвращает ошибку, если пакетное сохранение выполнить не удалось.
	SaveBatchURL(ctx context.Context, urlBatch []model.URLBatchRequestDto) ([]string, error)

	// GetUsersURLs возвращает список URL, созданных текущим пользователем.
	//
	// Идентификатор пользователя ожидается в переданном контексте.
	// Возвращает список моделей ответа model.GetUserURLsResponseModel или ошибку,
	// если данные пользователя не найдены либо произошла ошибка хранилища.
	GetUsersURLs(ctx context.Context) ([]model.GetUserURLsResponseModel, error)
}
